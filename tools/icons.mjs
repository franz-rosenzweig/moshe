// Writes frontend/src/lib/icons.js: the Lucide icons the app uses (ISC
// licence), as the inside of an <svg viewBox="0 0 24 24">. Run it after
// adding a name here: docker run … node tools/icons.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const dir = new URL('../frontend/node_modules/lucide-static/icons/', import.meta.url);
// the interface's own
const UI = `inbox archive folder-plus panel-left panel-right list-filter square-pen chevron-left chevron-right chevron-down share search
gauge target chart-line circle-ellipsis ellipsis x check plus trash-2 star paperclip message-square highlighter link image table sigma code quote
list list-ordered heading bold italic strikethrough eye file-text files file clock calendar tag tags settings download upload printer mail
split merge copy scissors undo-2 redo-2 rotate-ccw history save lock lock-open columns-2 rows-2 maximize-2 minimize-2 focus pilcrow type
external-link grip-vertical arrow-up-down info circle-check circle square-check keyboard languages log-out send message-circle hard-drive-download
sliders-vertical circle-plus eraser hand lasso ellipsis-vertical book-open-text file-plus pen-line minus`;
// what a group, a filter or a project may wear
const GROUP = `file-text files folder folder-open book book-open book-marked book-text library notebook notebook-pen scroll sticky-note clipboard
newspaper graduation-cap languages mic briefcase wrench feather pen-tool pencil palette rabbit popcorn heart music globe house coffee camera film
lightbulb rocket flag bookmark sparkles flame leaf sun moon zap shield lock key map compass anchor plane car bike gift puzzle gamepad-2
trophy crown gem smile users user baby dog cat bird fish tree-pine flower-2 mountain waves umbrella utensils pizza wine apple layers
layout-grid box package database terminal cpu flask-conical microscope atom brain stethoscope pill scale gavel landmark building church
hand-heart handshake messages-square send glasses mountain-snow sunrise wand-sparkles star calendar clock mail archive inbox tag filter
chart-line target paperclip image quote list code highlighter message-square`;
const names = [...new Set((UI + ' ' + GROUP).split(/\s+/u).filter(Boolean))];
const out = {};
for (const n of names) {
  const f = new URL(`${n}.svg`, dir);
  if (!existsSync(f)) { console.error('missing', n); continue; }
  const svg = readFileSync(f, 'utf8');
  out[n] = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s*\n\s*/gu, '').trim();
}
const groupIcons = [...new Set(GROUP.split(/\s+/u).filter((n) => out[n]))];
writeFileSync(new URL('../frontend/src/lib/icons.js', import.meta.url),
  '// Generated by tools/icons.mjs from lucide-static (ISC licence). Do not edit by hand.\n'
  + `export const ICONS = ${JSON.stringify(out, null, 0).replace(/","/gu, '",\n"')};\n`
  + `export const GROUP_ICONS = ${JSON.stringify(groupIcons)};\n`);
console.log(Object.keys(out).length, 'icons');
